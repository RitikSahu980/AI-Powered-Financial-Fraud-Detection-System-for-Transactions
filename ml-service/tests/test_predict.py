def test_predict_response_does_not_leak_engineered_features_or_derived_values(client: TestClient) -> None:
    """
    origBalanceDiff / destBalanceDiff are internal computation details, and
    confidence / risk_level are Spring Boot's responsibility per the frozen
    contract - none of these must ever appear in this service's response.
    """
    payload = {
        "step": 1,
        "type": "TRANSFER",
        "amount": 181,
        "oldbalanceOrg": 181,
        "newbalanceOrig": 0,
        "oldbalanceDest": 0,
        "newbalanceDest": 0,
    }
    response = client.post("/predict", json=payload)
    body = response.json()
    assert "origBalanceDiff" not in body
    assert "destBalanceDiff" not in body
    assert "confidence" not in body
    assert "risk_level" not in body
